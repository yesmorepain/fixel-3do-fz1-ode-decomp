"""Recreate the files derived from Fixel's firmware, which this repository does not ship.

Download the official FZ-1 ODE firmware ("rev 1.0") from https://github.com/fixelsan/3do-ode-firmware/releases,
then run (any OS, Python 3.8+):

    python3 tools/setup_from_official.py path/to/update.ode

It checks the file is exactly the official release, then writes:
  original/update.ode            the reference image (compare target)
  fpga_bitstream.bin             the FPGA bitstream extracted from it
  source/src/fpga_bitstream.bin  the same, where the source build expects it
  piode2.elf, functions.tsv, piode2_disasm.s, ghidra_symbols.txt, piode2_symbols.ld, db.json
                                 regenerated by tools/analyze.py from the image and the naming tables
"""
import hashlib, os, shutil, subprocess, sys

OFFICIAL_SHA256 = "5e98519d83c22605031a182acb6ecb3f4391aef2b922b02ec4ccb38918cf2fec"
OFFICIAL_SIZE = 145676
BITSTREAM_OFFSET = 0x1001f945 - 0x10010000     # file offset of the iCE40 bitstream
BITSTREAM_SIZE = 71338

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def write(rel, data):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)
    print("wrote", rel)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    data = open(sys.argv[1], "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if len(data) != OFFICIAL_SIZE or digest != OFFICIAL_SHA256:
        sys.exit("This is not the official FZ-1 ODE firmware rev 1.0\n  size %d (want %d)\n  sha256 %s\n  want   %s"
                 % (len(data), OFFICIAL_SIZE, digest, OFFICIAL_SHA256))
    print("official update.ode rev 1.0: OK", flush=True)

    bitstream = data[BITSTREAM_OFFSET:BITSTREAM_OFFSET + BITSTREAM_SIZE]
    if not bitstream.startswith(b"\xff\x00") or b"\x7e\xaa\x99\x7e" not in bitstream[:256]:
        sys.exit("bitstream not found at the expected offset")
    write("original/update.ode", data)
    write("fpga_bitstream.bin", bitstream)
    write("source/src/fpga_bitstream.bin", bitstream)

    print("running tools/analyze.py ...", flush=True)
    subprocess.run([sys.executable, "-I", os.path.join(ROOT, "tools", "analyze.py"),
                    os.path.join(ROOT, "original", "update.ode"), ROOT], check=True)
    print("done. Build the source as described in the README.")


if __name__ == "__main__":
    main()
